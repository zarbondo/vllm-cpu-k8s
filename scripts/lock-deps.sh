#!/usr/bin/env bash
# Re-generates the pinned requirement files of both images.
#
#   docker/vllm/requirements.txt             <- docker/vllm/requirements.in
#   docker/model-downloader/requirements.txt <- docker/model-downloader/requirements.in
#
# Uses a local `uv` if present, otherwise runs uv inside a python container,
# so only Docker is required. Needs access to PyPI, download.pytorch.org and GitHub.
set -euo pipefail

UV_VERSION="0.13.7"
EXCLUDE_NEWER="${EXCLUDE_NEWER:-}"   # e.g. 2026-11-09 to make the resolution time-stable
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

uv_run() {
  if command -v uv >/dev/null 2>&1; then
    uv "$@"
  else
    docker run --rm -v "$ROOT:/src" -w /src -e UV_NO_CACHE=1 python:3.12-slim-trixie \
      sh -c "pip install -q uv==${UV_VERSION} && uv $(printf '%q ' "$@")"
  fi
}

common=(--python-version 3.12 --no-header --annotation-style line)
[[ -n "$EXCLUDE_NEWER" ]] && common+=(--exclude-newer "$EXCLUDE_NEWER")

# vLLM image: CPU torch from the PyTorch index, glibc 2.39+ (Debian trixie base image)
uv_run pip compile docker/vllm/requirements.in "${common[@]}" \
  --python-platform x86_64-manylinux_2_39 \
  --torch-backend cpu --index-strategy unsafe-best-match \
  -o docker/vllm/requirements.lock.tmp
{
  echo "# Fully pinned dependency set for the vLLM CPU image (python 3.12, linux x86_64, glibc >= 2.39)."
  echo "# Generated by scripts/lock-deps.sh from docker/vllm/requirements.in - do not edit by hand."
  echo "# Installed with \`pip install --no-deps\`, so nothing outside this list can get into the image."
  echo "--extra-index-url https://download.pytorch.org/whl/cpu"
  echo
  cat docker/vllm/requirements.lock.tmp
} > docker/vllm/requirements.txt
rm -f docker/vllm/requirements.lock.tmp

# Downloader image: alpine (musl), every package hash-pinned
uv_run pip compile docker/model-downloader/requirements.in "${common[@]}" \
  --python-platform x86_64-unknown-linux-musl --generate-hashes \
  -o docker/model-downloader/requirements.txt

echo "Done. Review the diff: git diff -- docker/*/requirements.txt"
